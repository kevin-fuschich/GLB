from pathlib import Path
import re
root=Path(__file__).resolve().parents[1]
import os
os.chdir(root)
root=Path('.')
links=[('index.html','Home'),('scores.html','Scores'),('standings.html','Standings'),('schedule.html','Schedule'),('teams.html','Teams'),('stats.html','Stats'),('events/donk_championship.html','DONK'),('how-it-works.html','How it works'),('account.html','Account'),('contribute.html','Claim & Create')]
def active(name):
 if name.startswith(('team','club','mascot-')): return 'teams.html'
 if name=='player.html': return 'teams.html'
 if name in ['box.html','boxscore.html','game.html','day.html']: return 'scores.html'
 if 'donk' in name or name=='turkey-sightings.html': return 'events/donk_championship.html'
 return name

def header(name,prefix):
 def nav():
  return ''.join(f'<a href="{prefix}{href}"'+(' aria-current="page"' if href==active(name) else '')+(' class="glb-header-claim"' if href=='contribute.html' else '')+'>'+label.replace('&','&amp;')+'</a>' for href,label in links)
 return f'''<!-- Shared GLB header: generated by scripts/build-site-header.py -->
<header class="site-header" id="glb-site-header">
  <div class="glb-header-bar">
    <a class="glb-header-brand" href="{prefix}index.html" aria-label="Global League Baseball home"><span class="glb-header-mark">GLB</span><span class="glb-header-name">Global League<br>Baseball</span></a>
    <nav class="glb-header-nav" aria-label="Primary">{nav()}</nav>
    <button id="navToggle" type="button" aria-label="Open menu" aria-expanded="false" aria-controls="mobileMenu">Menu <span aria-hidden="true">☰</span></button>
  </div>
  <nav id="mobileMenu" aria-label="Mobile navigation" hidden>{nav()}</nav>
</header>'''
exclude={'SYSTEM.html','test.html','health.html','boxscore_stresstest.html','team-light-test.html','team-spokane-alloys.html.html','game_light.html'}
paths=list(root.glob('*.html'))+[Path('events/donk_championship.html')]
count=0
for p in paths:
 if p.name in exclude: continue
 # Nested event source may be outside sparse checkout.
 if not p.exists(): continue
 s=p.read_text()
 if not s.strip() or '<body' not in s: continue
 # Pure redirect stubs do not have a rendered site page.
 if len(s)<2000 and ('location.replace' in s or 'http-equiv="refresh"' in s): continue
 prefix='../' if p.parent!=root else ''
 if 'id="glb-site-header"' in s:
  s=re.sub(r'<!-- Shared GLB header:.*?</header>',header(p.name,prefix),s,count=1,flags=re.S)
 else:
  h=re.search(r'<header\b[^>]*>.*?</header>',s,re.S|re.I)
  if h and ('site-header' in h[0] or p.name in ['contribute.html','how-it-works.html']):
   s=s[:h.start()]+header(p.name,prefix)+s[h.end():]
  else:
   # Keep page-specific headings and logos beneath the shared league navigation.
   s=re.sub(r'(<body\b[^>]*>)',lambda m:m[0]+'\n'+header(p.name,prefix),s,count=1)
   # Remove old inline league navigation from content headings only.
   if h:
    old=h[0]; new=re.sub(r'<nav\b.*?</nav>','',old,flags=re.S)
    s=s.replace(old,new,1)
 # Remove old menu click listeners; common script owns all menu behavior.
 def strip_listener(m):
  tag=m[0]
  for hit in list(re.finditer(r'\b(navToggle|toggle|t)\.addEventListener\(\s*[\'\"]click[\'\"]',tag))[::-1]:
   start=hit.start(); pos=tag.index('(',start); depth=1; i=pos+1; quote=None
   while i<len(tag) and depth:
    c=tag[i]
    if quote:
     if c==quote and tag[i-1]!='\\':quote=None
    elif c in "\"'`":quote=c
    elif c=='(':depth+=1
    elif c==')':depth-=1
    i+=1
   code=tag[start:i]
   if 'classList.toggle' in code and ('mobileMenu' in tag or "getElementById('mobileMenu')" in code):
    if i<len(tag) and tag[i]==';':i+=1
    tag=tag[:start]+tag[i:]
  return tag
 s=re.sub(r'<script\b[^>]*>.*?</script>',strip_listener,s,flags=re.S)
 if 'site-header.css?v=' not in s:
  s=s.replace('</head>',f'<link rel="stylesheet" href="{prefix}site-header.css?v=20261112">\n<script defer src="{prefix}scripts/site-header.js?v=20261112"></script>\n</head>',1)
 p.write_text('\n'.join(line.rstrip() for line in s.split('\n')));count+=1
for p in root.glob('scripts/*.js'):
 if p.name in ['site-header.js']:continue
 s=p.read_text()
 if 'mobileMenu' in s:
  # Team content modules previously also owned their own menu listener.
  s=re.sub(r"  toggle\.addEventListener\('click', \(\) => \{.*?\n  \}\);\n",'',s,flags=re.S)
  p.write_text(s)
print('Updated',count,'pages')
